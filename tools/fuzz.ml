type outcome = {
  status : [ `Exit of int | `Signal of int | `Timeout ];
  out : string;
  err : string;
}

let read_file path =
  try
    let ch = open_in_bin path in
    let n = in_channel_length ch in
    let s = really_input_string ch n in
    close_in ch; s
  with _ -> ""

let devnull = lazy (Unix.openfile "/dev/null" [Unix.O_RDONLY] 0)

let tmp_out = lazy (Filename.temp_file "ppfuzz" ".out")
let tmp_err = lazy (Filename.temp_file "ppfuzz" ".err")

let run_backend (args : string list) (file : string) : outcome =
  let out_f = Lazy.force tmp_out and err_f = Lazy.force tmp_err in
  let fd_out = Unix.openfile out_f [Unix.O_WRONLY; Unix.O_CREAT; Unix.O_TRUNC] 0o600 in
  let fd_err = Unix.openfile err_f [Unix.O_WRONLY; Unix.O_CREAT; Unix.O_TRUNC] 0o600 in
  let argv = Array.of_list (!pp_bin :: args @ [file]) in
  let pid =
    try Unix.create_process !pp_bin argv (Lazy.force devnull) fd_out fd_err
    with Unix.Unix_error (e, _, _) ->
      Unix.close fd_out; Unix.close fd_err;
      prerr_endline ("fatal: cannot execute " ^ !pp_bin ^ ": " ^ Unix.error_message e);
      exit 2
  in
  Unix.close fd_out; Unix.close fd_err;
  let deadline = Unix.gettimeofday () +. float_of_int !timeout_ms /. 1000.0 in
  let rec wait () =
    let (p, st) = Unix.waitpid [Unix.WNOHANG] pid in
    if p = 0 then begin
      if Unix.gettimeofday () > deadline then begin
        (try Unix.kill pid Sys.sigkill with _ -> ());
        ignore (Unix.waitpid [] pid);
        `Timeout
      end else begin
        Unix.sleepf 0.002;
        wait ()
      end
    end else
      match st with
      | Unix.WEXITED n -> `Exit n
      | Unix.WSIGNALED s | Unix.WSTOPPED s -> `Signal s
  in
  let status = wait () in
  { status; out = read_file out_f; err = read_file err_f }

(* ------------------------------------------------------------ Verdicts -- *)

type verdict =
  | Pass
  | Mismatch of string   (* signature *)
  | BothError of string  (* signature *)
  | Crash of string      (* signature *)

(* normalize for signature grouping: quoted strings -> "S", digit runs -> #,
   newlines -> spaces, cap length.  Aggressive on purpose: signatures should
   count BUG CLASSES, not distinct payloads. *)
let norm ?(max_len = 48) s =
  let b = Buffer.create (String.length s) in
  let n = String.length s in
  let i = ref 0 in
  let last_hash = ref false in
  while !i < n do
    let c = s.[!i] in
    if c = '"' || (c = '\\' && !i + 1 < n && s.[!i + 1] = '"') then begin
      (* skip a quoted span, possibly backslash-escaped; emit a placeholder *)
      let esc = c = '\\' in
      i := !i + (if esc then 2 else 1);
      let closed = ref false in
      while not !closed && !i < n do
        if esc && s.[!i] = '\\' && !i + 1 < n && s.[!i + 1] = '"' then begin
          i := !i + 2; closed := true
        end else if (not esc) && s.[!i] = '"' then begin
          incr i; closed := true
        end else incr i
      done;
      Buffer.add_string b "\"S\"";
      last_hash := false
    end else begin
      if c >= '0' && c <= '9' then begin
        if not !last_hash then Buffer.add_char b '#';
        last_hash := true
      end else begin
        last_hash := false;
        if c = '\n' then Buffer.add_char b ' ' else Buffer.add_char b c
      end;
      incr i
    end
  done;
  let s = Buffer.contents b in
  if String.length s > max_len then String.sub s 0 max_len else s

(* extract a stable error tag from stderr *)
let error_tag (err : string) : string =
  let lines = String.split_on_char '\n' err in
  let fatal =
    List.fold_left (fun acc l ->
      let prefix = "Fatal error: exception " in
      let clean = "pp: error: " in
      if String.length l > String.length prefix
         && String.sub l 0 (String.length prefix) = prefix
      then Some (String.sub l (String.length prefix)
                   (String.length l - String.length prefix))
      else if String.length l > String.length clean
              && String.sub l 0 (String.length clean) = clean
      then
        (* pp's clean error line carries the raw message; re-wrap it in the
           Failure("…") shape so the normalization below applies unchanged. *)
        Some (Printf.sprintf "Failure(\"%s\")"
                (String.sub l (String.length clean)
                   (String.length l - String.length clean)))
      else acc) None lines
  in
  match fatal with
  | None -> "no-fatal-line"
  | Some rest ->
      (* Failure("msg") — pull out msg, strip nested builtin wrappers *)
      let msg =
        if String.length rest > 9 && String.sub rest 0 9 = "Failure(\"" then begin
          let inner = String.sub rest 9 (String.length rest - 9) in
          let inner =
            match String.rindex_opt inner '"' with
            | Some i -> String.sub inner 0 i
            | None -> inner in
          (* repeatedly strip "builtin 'X' failed: " *)
          let rec strip s =
            let pfx = "builtin '" in
            if String.length s > String.length pfx
               && String.sub s 0 (String.length pfx) = pfx then
              match String.index_opt s ':' with
              | Some i when i + 2 <= String.length s ->
                  strip (String.sub s (i + 2) (String.length s - i - 2))
              | _ -> s
            else s
          in
          let m = strip inner in
          (* drop value payloads: "type mismatch: expected int, got false"
             and friends group by the ", got"-free prefix *)
          let m =
            let pat = ", got " in
            let rec find i =
              if i + String.length pat > String.length m then None
              else if String.sub m i (String.length pat) = pat then Some i
              else find (i + 1) in
            match find 0 with
            | Some i -> String.sub m 0 i ^ ", got _"
            | None -> m in
          "Failure:" ^ m
        end else
          (* non-Failure exception: keep constructor name only *)
          (match String.index_opt rest '(' with
           | Some i -> String.sub rest 0 i
           | None -> rest)
      in
      norm msg

let sig_of_verdict = function
  | Pass -> None
  | Mismatch s | BothError s | Crash s -> Some s



(* -------------------------------------------------------------- Shrink -- *)

(* Since gen_program renders directly, the shrinker works on a re-parsed sx
   tree of the rendered program.  Tiny parser for our OWN rendered output;
   atoms are whitespace-delimited and generated string literals never contain
   quotes, backslashes, or brackets. *)

let parse_program (src : string) : sx list =
  let n = String.length src in
  let pos = ref 0 in
  let peek () = if !pos < n then Some src.[!pos] else None in
  let rec skip_ws () =
    match peek () with
    | Some (' ' | '\n' | '\t') -> incr pos; skip_ws ()
    | _ -> ()
  in
  let rec parse_one () : sx =
    skip_ws ();
    match peek () with
    | Some '(' -> incr pos; S (parse_seq ')')
    | Some '[' -> incr pos; V (parse_seq ']')
    | Some '{' -> incr pos; C (parse_seq '}')
    | Some '"' ->
        let start = !pos in
        incr pos;
        while !pos < n && src.[!pos] <> '"' do incr pos done;
        incr pos;
        A (String.sub src start (!pos - start))
    | Some _ ->
        let start = !pos in
        let stop c = c = ' ' || c = '\n' || c = '\t' || c = '(' || c = ')'
                     || c = '[' || c = ']' || c = '{' || c = '}' in
        while !pos < n && not (stop src.[!pos]) do incr pos done;
        A (String.sub src start (!pos - start))
    | None -> failwith "parse_program: eof"
  and parse_seq close =
    skip_ws ();
    match peek () with
    | Some c when c = close -> incr pos; []
    | Some _ -> let x = parse_one () in x :: parse_seq close
    | None -> failwith "parse_program: unterminated"
  in
  let rec top () =
    skip_ws ();
    if !pos >= n then [] else let x = parse_one () in x :: top ()
  in
  top ()

(* enumerate node count; replace node #target (preorder, roots first) *)
let rec count_nodes sx =
  match sx with
  | A _ -> 1
  | S xs | V xs | C xs -> 1 + List.fold_left (fun a x -> a + count_nodes x) 0 xs

let replace_node (sx : sx) (target : int) (repl : sx) : sx =
  let idx = ref (-1) in
  let rec go sx =
    incr idx;
    if !idx = target then repl
    else match sx with
      | A _ -> sx
      | S xs -> S (List.map go xs)
      | V xs -> V (List.map go xs)
      | C xs -> C (List.map go xs)
  in
  go sx

let node_at (sx : sx) (target : int) : sx =
  let idx = ref (-1) in
  let found = ref None in
  let rec go sx =
    incr idx;
    if !idx = target then found := Some sx;
    (match sx with
     | A _ -> ()
     | S xs | V xs | C xs -> List.iter go xs)
  in
  go sx;
  match !found with Some x -> x | None -> A "?"

let prog_size forms = String.length (render_program forms)

(* candidate reductions for a program, in decreasing aggressiveness *)
let shrink_candidates (forms : sx list) : sx list list =
  let cands = ref [] in
  let add c = cands := c :: !cands in
  let nf = List.length forms in
  (* 1. drop a top-level form *)
  if nf > 1 then
    for i = 0 to nf - 1 do
      add (List.filteri (fun j _ -> j <> i) forms)
    done;
  (* 2. hoist a child over its parent; 3. replace subtree with a literal *)
  List.iteri (fun fi form ->
    let n = count_nodes form in
    for node_i = 1 to n - 1 do        (* skip the root of the form itself *)
      (match node_at form node_i with
       | S (_ :: args) when args <> [] ->
           List.iter (fun arg ->
             add (List.mapi (fun j f ->
               if j = fi then replace_node f node_i arg else f) forms)
           ) args
       | _ -> ());
      (match node_at form node_i with
       | A a ->
           (* shrink integer atoms *)
           (match int_of_string_opt a with
            | Some v when v <> 0 && v <> 1 ->
                let v' = if abs v > 4 then v / 2 else (if v > 0 then v - 1 else v + 1) in
                add (List.mapi (fun j f ->
                  if j = fi then replace_node f node_i (A (string_of_int v')) else f) forms)
            | _ -> ())
       | _ ->
           List.iter (fun r ->
             add (List.mapi (fun j f ->
               if j = fi then replace_node f node_i r else f) forms))
             [A "0"; A "1"; A "true"; A "nil"; A "\"a\""])
    done
  ) forms;
  List.rev !cands

(* `.pp` dispatches to the brace reader; every program this
   fuzzer generates is sexpr text (the `sx` tree's printer emits classic
   S-expressions), so the scratch file keeps the `.ppl` extension — the
   sexpr surface is still fully supported, just no longer the default for
   `.pp`. `--roundtrip-braces` (below) also relies on this: it refuses a
   file whose extension already dispatches to the brace reader. *)
let prog_file = lazy (Filename.temp_file "ppfuzz" ".ppl")

(* The reader round-trip check (sexpr -> braces -> re-read; AST +
   LAW-20 hash equality), run in-process by the interpreter itself. *)
let run_roundtrip (src : string) : outcome =
  let f = Lazy.force prog_file in
  let ch = open_out f in
  output_string ch src; close_out ch;
  run_backend ["--roundtrip-braces"] f

(* Single walker run — writes the program file and runs `pp f`. *)
let run_walker (src : string) : outcome =
  let f = Lazy.force prog_file in
  let ch = open_out f in
  output_string ch src; close_out ch;
  run_backend [] f

(* Single-engine verdict: a roundtrip failure always gates as Mismatch.
   Otherwise, check the walker outcome: crashes are hard failures,
   non-zero exits with known error tags are soft (BothError). *)
let judge_walker (w : outcome) : verdict =
  let crash_of o =
    match o.status with
    | `Timeout -> Some "crash:timeout"
    | `Signal s -> Some (Printf.sprintf "crash:signal-%d" s)
    | `Exit n when n > 128 -> Some (Printf.sprintf "crash:exit-%d" n)
    | _ -> None
  in
  match crash_of w with
  | Some s -> Crash s
  | None ->
      if w.status = `Exit 0 then Pass
      else
        let tag = error_tag w.err in
        BothError ("error:" ^ tag)

let judge_full (rt : outcome) (w : outcome) : verdict =
  if rt.status <> `Exit 0 then Mismatch ("roundtrip:" ^ error_tag rt.err)
  else judge_walker w
let special_form_heads =
  ["def"; "defmacro"; "defnode"; "let"; "let*"; "module"; "import";
   "load"; "load-module"; "quote"; "quasiquote"; "unquote"; "fn"; "match"; "effect";
   "perform"; "with-handler"; "with-config"; "island"; "node"]

let is_special_form_head s = List.mem s special_form_heads

let is_literal_atom s =
  (try ignore (int_of_string s); true with _ ->
   try ignore (float_of_string s); true with _ ->
   (String.length s >= 2 && s.[0] = '"' && s.[String.length s - 1] = '"')
   || s = "true" || s = "false" || s = "nil")

type eligible = { e_form : int; e_node : int }

(* Collect eligible wrap positions by iterating with node_at directly.
   This guarantees index consistency with replace_node/node_at. *)
(* Simplified context check: only reject positions inside quote/quasiquote
   or inside load/import/defmacro (non-expression argument positions). *)
let is_expr_position form target =
  let idx = ref (-1) in
  let ok = ref true in
  let found = ref false in
  let rec count sx =
    incr idx;
    if !idx = target then ok := false
    else if not !found then match sx with
    | A _ -> ()
    | S xs | V xs | C xs -> List.iter count xs
  in
  let rec go sx =
    incr idx;
    if !idx = target then ()
    else if not !found then match sx with
    | A _ -> ()
    | V xs -> List.iter go xs
    | C xs -> List.iter go xs
    | S (A head :: args) ->
        let skip = head = "quote" || head = "quasiquote"
                   || head = "load" || head = "load-module" || head = "import"
                   || head = "defmacro" || head = "def" || head = "fn" in
        if skip then
          List.iter count (A head :: args)
        else if head = "let" || head = "let*" then
          (* Count head and binding vector; walk body normally *)
          let () = count (A head) in
          (match args with
           | bind :: rest -> count bind; List.iter go rest
           | _ -> List.iter go args)
        else if head = "match" then
          let () = count (A head) in
          (match args with
           | scrut :: arms ->
               go scrut;
               List.iter (fun arm ->
                 match arm with
                 | S parts when List.length parts >= 2 ->
                     let n = List.length parts in
                     let () = incr idx in
                     if !idx = target then ok := false
                     else begin
                       List.iter count (List.filteri (fun i _ -> i < n - 1) parts);
                       go (List.nth parts (n - 1))
                     end
                 | _ -> go arm
               ) arms
           | _ -> ())
        else
          List.iter go (A head :: args)
    | S xs ->
        List.iter go xs
  in
  go form;
  !ok

let collect_eligible forms =
  let result = ref [] in
  List.iteri (fun fi form ->
    let n = count_nodes form in
    for node_i = 1 to n - 1 do
      let sx = node_at form node_i in
      let eligible = match sx with
        | A s -> is_literal_atom s
        | S (A head :: _) -> not (is_special_form_head head)
        | S (_ :: _) -> true
        | _ -> false
      in
      if eligible && is_expr_position form node_i then
        result := { e_form = fi; e_node = node_i } :: !result
    done
  ) forms;
  List.rev !result

let apply_do_wrap (e : sx) : sx = S [A "do"; e]

let apply_let_wrap (e : sx) : sx =
  let name = fresh "t" in
  S [A "let"; V [A name; e]; A name]

let apply_eta_wrap (e : sx) : sx =
  let name = fresh "t" in
  S [S [A "fn"; S [A name]; A name]; e]

let derive_twin (src : string) : string option =
  let forms = parse_program src in
  let eligible = collect_eligible forms in
  if eligible = [] then None
  else begin
    let k = min (List.length eligible) (rint 1 3) in
    let used = Hashtbl.create 3 in
    let picks = ref [] in
    while List.length !picks < k do
      let idx = Random.int (List.length eligible) in
      if not (Hashtbl.mem used idx) then begin
        Hashtbl.add used idx true;
        picks := (List.nth eligible idx) :: !picks
      end
    done;
    let transforms = [apply_do_wrap; apply_let_wrap; apply_eta_wrap] in
    let sorted_picks = List.sort (fun a b ->
      let c = compare a.e_form b.e_form in
      if c <> 0 then c else compare b.e_node a.e_node
    ) !picks in
    let new_forms = List.fold_left (fun acc picked ->
      let form = List.nth acc picked.e_form in
      let e = node_at form picked.e_node in
      let t = List.nth transforms (Random.int 3) in
      let wrapped = replace_node form picked.e_node (t e) in
      List.mapi (fun j f -> if j = picked.e_form then wrapped else f) acc
    ) forms sorted_picks in
    Some (render_program new_forms)
  end

let first_diff_lines a b =
  let la = String.split_on_char '\n' a and lb = String.split_on_char '\n' b in
  let rec go la lb =
    match la, lb with
    | [], [] -> ("", "")
    | x :: ra, y :: rb -> if x = y then go ra rb else (x, y)
    | x :: _, [] -> (x, "<eof>")
    | [], y :: _ -> ("<eof>", y)
  in
  go la lb

let judge_meta (a : outcome) (b : outcome) : verdict =
  let crash_of side o = match o.status with
    | `Timeout -> Some (Printf.sprintf "crash:%s:timeout" side)
    | `Signal s -> Some (Printf.sprintf "crash:%s:signal-%d" side s)
    | `Exit n when n > 128 -> Some (Printf.sprintf "crash:%s:exit-%d" side n)
    | _ -> None
  in
  match crash_of "p" a, crash_of "t" b with
  | Some s, _ | _, Some s -> Crash s
  | None, None ->
      let a_ok = a.status = `Exit 0 and b_ok = b.status = `Exit 0 in
      if a_ok && b_ok then begin
        if a.out <> b.out then
          let (a_l, b_l) = first_diff_lines a.out b.out in
          Mismatch ("metamorphic:outdiff:" ^ norm ~max_len:28 a_l ^ "|" ^ norm ~max_len:28 b_l)
        else if a.err <> b.err then
          let (a_l, b_l) = first_diff_lines a.err b.err in
          Mismatch ("metamorphic:logdiff:" ^ norm ~max_len:28 a_l ^ "|" ^ norm ~max_len:28 b_l)
        else Pass
      end
      else if a_ok && not b_ok then
        Mismatch ("metamorphic:exitdiff:t-err:" ^ error_tag b.err)
      else if b_ok && not a_ok then
        Mismatch ("metamorphic:exitdiff:p-err:" ^ error_tag a.err)
      else
        let ta = error_tag a.err and tb = error_tag b.err in
        if ta = tb then Pass
        else Mismatch ("metamorphic:both-error:" ^ ta ^ "|" ^ tb)

(* Run a single program through pp f and return the outcome *)
let run_single (src : string) : outcome =
  let f = Lazy.force prog_file in
  let ch = open_out f in output_string ch src; close_out ch;
  run_backend [] f

let run_metamorphic (src : string) (twin : string) : verdict =
  let p_out = run_single src in
  let t_out = run_single twin in
  judge_meta p_out t_out

let is_meta_signature s =
  String.length s >= 12 && String.sub s 0 12 = "metamorphic:"

let shrink (src : string) (signature : string) : string =
  let is_meta = is_meta_signature signature in
  let execs = ref 0 in
  let same_sig forms =
    if !execs >= !shrink_budget then false
    else begin
      incr execs;
      if is_meta then begin
        let text = render_program forms in
        let h = Hashtbl.hash text in
        Random.full_init [| h |];
        name_counter := 0;
        match derive_twin text with
        | Some twin ->
            let p_out = run_single text in
            let t_out = run_single twin in
            sig_of_verdict (judge_meta p_out t_out) = Some signature
        | None -> false
      end else begin
        let w = run_walker (render_program forms) in
        let rt = run_roundtrip (render_program forms) in
        sig_of_verdict (judge_full rt w) = Some signature
      end
    end
  in
  let rec fixpoint forms =
    if !execs >= !shrink_budget then forms
    else begin
      let size0 = prog_size forms in
      let better =
        List.find_opt (fun c -> prog_size c < size0 && same_sig c)
          (shrink_candidates forms)
      in
      match better with
      | Some c -> fixpoint c
      | None -> forms
    end
  in
  try render_program (fixpoint (parse_program src))
  with _ -> src   (* shrinker must never lose the repro *)

