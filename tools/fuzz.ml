(* pp fuzzer — generates random pp programs and checks them via a
   single-engine metamorphic + roundtrip oracle.

   Every generated program is pushed through `pp f` (the tree-walker),
   AND through `pp --roundtrip-braces f`, which (in one process)
   reads the sexpr AST, prints it as location-preserving brace text
   (src/printer_braces.ml), re-reads that with the brace reader
   MISMATCH (`roundtrip:*` signature), shrunk like any other.

   Metamorphic oracle: every generated program P is ALSO transformed into a
   twin T(P) by 1–3 semantics-preserving wraps (do, let-identity, or
   eta-identity) at random eligible positions, then P and T(P) are run
   through the SAME single backend (`pp f`) and compared. Any divergence is
   a single-engine bug.

   OCaml stdlib + unix only.  Build+run:  dune exec ./tools/fuzz.exe -- ARGS
   Fully deterministic given --seed: program i is generated from
   Random.full_init [| seed; i |], so any program can be regenerated with
   --seed S --start i --count 1 (or inspected with --dump i).

   Grammar notes (verified against src/primitives.ml, stdlib/list.pp, reader.ml):
   - builtins used: + - * / mod < > <= >= = not list cons car cdr nil? print
     string-append string-length string-trim string-sub string-index
     number->string string->number vector vector-get hash-map hash-map-get
   - stdlib fns (require (load ".../stdlib/list.pp")): map filter foldl range take length
   - `and`/`or` are reader-level special forms (desugar to if) — safe.
   - (def x 5) is a VALUE binding (evaluated at definition time, sequential
     at top level) — generated by stmt_def_value and referenced by later
     statements. Function defs still always take >= 1 parameter.
   - `let` is parallel (bindings see the OUTER env).
   - car/cdr of nil returns nil (no error); still, car is only applied to
     statically-nonempty lists so arithmetic on the element is well-typed.
   - / and mod only ever get a nonzero positive literal divisor.
   - No random / wall-clock / network-island forms are ever generated;
     pinned file: islands over a fixed fixture are sampled in `full`.
   - `defmacro`: `stmt_defmacro` (full only) defines a fresh,
     well-scoped macro that doubles its (always-literal) argument via
     `list`/`quote`, then calls it — exercises the shared expansion point
     (macro.ml). *)

