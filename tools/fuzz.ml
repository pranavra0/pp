let parse_cli () =
  let rec go = function
    | [] -> ()
    | "--seed" :: v :: r -> seed := int_of_string v; go r
    | "--count" :: v :: r -> count := int_of_string v; go r
    | "--max-depth" :: v :: r -> max_depth := int_of_string v; go r
    | "--timeout-ms" :: v :: r -> timeout_ms := int_of_string v; go r
    | "--out" :: v :: r -> out_dir := v; go r
    | "--grammar" :: v :: r ->
        if v <> "core" && v <> "full" then usage (); grammar := v; go r
    | "--start" :: v :: r -> start_iter := int_of_string v; go r
    | "--dump" :: v :: r -> dump_iter := int_of_string v; go r
    | "--pp" :: v :: r -> pp_bin := v; go r
    | "--stdlib" :: v :: r -> stdlib_path := v; go r
    | "--shrink-budget" :: v :: r -> shrink_budget := int_of_string v; go r
    | "--no-metamorphic" :: r -> no_metamorphic := true; go r
    | ("--help" | "-h") :: _ -> usage ()
    | x :: _ -> prerr_endline ("unknown argument: " ^ x); usage ()
  in
  go (List.tl (Array.to_list Sys.argv));
  if !stdlib_path = "" then
    stdlib_path := Filename.concat (Sys.getcwd ()) "stdlib/list.pp"

(* ------------------------------------------------------------- S-exprs -- *)

type sx =
  | A of string        (* atom, rendered verbatim *)
  | S of sx list       (* ( ... ) *)
  | V of sx list       (* [ ... ] *)
  | C of sx list       (* { ... } *)

let rec render_sx buf sx =
  match sx with
  | A s -> Buffer.add_string buf s
  | S xs -> Buffer.add_char buf '('; render_list buf xs; Buffer.add_char buf ')'
  | V xs -> Buffer.add_char buf '['; render_list buf xs; Buffer.add_char buf ']'
  | C xs -> Buffer.add_char buf '{'; render_list buf xs; Buffer.add_char buf '}'

and render_list buf = function
  | [] -> ()
  | [x] -> render_sx buf x
  | x :: rest -> render_sx buf x; Buffer.add_char buf ' '; render_list buf rest

let render_program (forms : sx list) : string =
  let buf = Buffer.create 512 in
  List.iter (fun f -> render_sx buf f; Buffer.add_char buf '\n') forms;
  Buffer.contents buf

(* ----------------------------------------------------------- Generator -- *)

type ty = TInt | TFloat | TBool | TStr | TList

type gvar = { vname : string; vty : ty; vne : bool }  (* vne: list known nonempty *)

type genv = {
  vars : gvar list;                  (* lexical, per-statement *)
  mutable fns : (string * int * bool) list;
                                     (* top-level int fns: name, arity, recursive.
                                        Args at call sites of RECURSIVE fns are
                                        wrapped in (mod _ 64): recursion depth
                                        stays bounded, so a one-sided timeout on
                                        a terminating-but-slow program (perf
                                        asymmetry, not semantics) cannot poison
                                        the ratchet. *)
  mutable stdlib : bool;             (* stdlib list.pp loaded *)
  mutable gvars : gvar list;         (* top-level (def x v) value bindings —
                                        sequential, so any later statement may
                                        reference them *)
}

let name_counter = ref 0
let fresh prefix = incr name_counter; Printf.sprintf "%s%d" prefix !name_counter

let rint lo hi = lo + Random.int (hi - lo + 1)
let flip p = Random.float 1.0 < p

(* weighted pick *)
let pick (choices : (int * (unit -> 'a)) list) : 'a =
  let total = List.fold_left (fun a (w, _) -> a + w) 0 choices in
  let n = Random.int total in
  let rec go acc = function
    | [] -> assert false
    | (w, f) :: rest -> if n < acc + w then f () else go (acc + w) rest
  in
  go 0 choices

let str_pool = [| "a"; "bc"; "xyz"; "hello"; "pp"; "zz"; "q0"; "lisp" |]
let gen_str_lit () = A ("\"" ^ str_pool.(Random.int (Array.length str_pool)) ^ "\"")
(* The reader's historical negative-literal bug (bare -5 lexing as a symbol)
   is fixed — reader.ml's '-' branch peeks the following digit — so negative
   int literals are generated again. Divisors for / and mod stay positive. *)
let gen_int_lit () = A (string_of_int (rint (-50) 100))
let gen_float_lit () =
  A (string_of_float (float_of_int (rint 0 40) /. 2.0))

let vars_of ty env = List.filter (fun v -> v.vty = ty) (env.vars @ env.gvars)
let has_vars ty env = vars_of ty env <> []
let pick_var ty env =
  let vs = vars_of ty env in
  (List.nth vs (Random.int (List.length vs))).vname

(* --- typed expression generators (mutually recursive) --- *)

let rec gen_int env d : sx =
  if d <= 0 then
    pick [
      4, (fun () -> gen_int_lit ());
      (if has_vars TInt env then 3 else 0), (fun () -> A (pick_var TInt env));
    ]
  else
    pick [
      3, (fun () -> gen_int_lit ());
      (if has_vars TInt env then 3 else 0), (fun () -> A (pick_var TInt env));
      4, (fun () ->
        let op = [| "+"; "-"; "*" |].(Random.int 3) in
        let n_args = if op <> "-" && flip 0.25 then 3 else 2 in
        let args = List.init n_args (fun _ -> gen_int env (d - 1)) in
        S (A op :: args));
      1, (fun () -> S [A "mod"; gen_int env (d - 1); A (string_of_int (rint 1 9))]);
      1, (fun () -> S [A "/"; gen_int env (d - 1); A (string_of_int (rint 1 9))]);
      2, (fun () -> S [A "if"; gen_bool env (d - 1); gen_int env (d - 1); gen_int env (d - 1)]);
      1, (fun () ->
        (* (let [x <int>] <int using x>) — binding evaluated in OUTER env *)
        let x = fresh "x" in
        let bind = gen_int env (d - 1) in
        let env' = { env with vars = { vname = x; vty = TInt; vne = false } :: env.vars } in
        S [A "let"; V [A x; bind]; gen_int env' (d - 1)]);
      (if env.fns <> [] then 2 else 0), (fun () ->
        let (f, arity, is_rec) = List.nth env.fns (Random.int (List.length env.fns)) in
        let arg () =
          let e = gen_int env (d - 1) in
          if is_rec then S [A "mod"; e; A "64"] else e in
        S (A f :: List.init arity (fun _ -> arg ())));
      1, (fun () -> S [A "string-length"; gen_string env (d - 1)]);
      1, (fun () -> S [A "string->number"; S [A "number->string"; gen_int env (d - 1)]]);
      1, (fun () ->
        (* string-index is int-or-nil; guard the nil case (pure, so the
           double evaluation is safe) *)
        let idx () = S [A "string-index"; gen_string env (d - 1); gen_str_lit ()] in
        let i1 = idx () in
        S [A "if"; S [A "nil?"; i1]; A "0"; i1]);
      (if env.stdlib then 1 else 0), (fun () -> S [A "length"; gen_list env (d - 1)]);
      (if env.stdlib then 1 else 0), (fun () -> S [A "foldl"; A "+"; A "0"; gen_list env (d - 1)]);
      1, (fun () -> S [A "car"; gen_list_ne env (d - 1)]);
      1, (fun () ->
        S [A "vector-get";
           V [gen_int env (d - 1); gen_int env (d - 1); gen_int env (d - 1)];
           A (string_of_int (rint 0 2))]);
      1, (fun () ->
        let k = fresh "k" in
        S [A "hash-map-get"; C [A (":" ^ k); gen_int env (d - 1)]; A (":" ^ k)]);
      1, (fun () ->
        (* immediate application ((fn (x) body) arg) *)
        let x = fresh "x" in
        let env' = { env with vars = { vname = x; vty = TInt; vne = false } :: env.vars } in
        S [S [A "fn"; S [A x]; gen_int env' (d - 1)]; gen_int env (d - 1)]);
      1, (fun () -> S [A "do"; gen_int env (d - 1); gen_int env (d - 1)]);
      2, (fun () -> gen_match TInt env d);
      (if env.stdlib then 1 else 0), (fun () ->
        (* (apply + <nonempty int list>) — apply concatenates the one
           segment and calls +, returning an int. Round-trips through braces
           as apply(+, …). *)
        S [A "apply"; A "+"; gen_list_ne env (d - 1)]);
    ]

(* A total, well-typed `(match <scrut> arm…)` producing type [ty].
   Every arm body is generated at [ty]; the scrutinee is an int so patterns are
   int literals / variables / `_` (never a list pattern against a scalar), and a
   final `_` arm guarantees no match-failure. Exercises guards (`pat if cond`)
   and — because the whole program is emitted as sexpr and also round-tripped
   through braces — the sexpr match reader and both printers. *)
and gen_match ty env d : sx =
  let gen e dd = match ty with
    | TInt -> gen_int e dd | TStr -> gen_string e dd | TBool -> gen_bool e dd
    | TFloat -> gen_float e dd | TList -> gen_list e dd in
  let scrut = gen_int env (d - 1) in
  let n = fresh "n" in
  let envn = { env with vars = { vname = n; vty = TInt; vne = false } :: env.vars } in
  S [A "match"; scrut;
     S [A (string_of_int (rint 0 4)); gen env (d - 1)];               (* literal arm *)
     S [A n; A "if"; S [A ">"; A n; A (string_of_int (rint 0 6))];    (* guarded var arm *)
        gen envn (d - 1)];
     S [A "_"; gen env (d - 1)]]                                      (* wildcard fallback *)

and gen_bool env d : sx =
  if d <= 0 then
    pick [
      2, (fun () -> A (if flip 0.5 then "true" else "false"));
      (if has_vars TBool env then 2 else 0), (fun () -> A (pick_var TBool env));
    ]
  else
    pick [
      2, (fun () -> A (if flip 0.5 then "true" else "false"));
      (if has_vars TBool env then 2 else 0), (fun () -> A (pick_var TBool env));
      4, (fun () ->
        let op = [| "<"; ">"; "<="; ">="; "=" |].(Random.int 5) in
        S [A op; gen_int env (d - 1); gen_int env (d - 1)]);
      1, (fun () -> S [A "="; gen_string env (d - 1); gen_string env (d - 1)]);
      1, (fun () -> S [A "not"; gen_bool env (d - 1)]);
      2, (fun () ->
        let op = if flip 0.5 then "and" else "or" in
        S [A op; gen_bool env (d - 1); gen_bool env (d - 1)]);
      1, (fun () -> S [A "nil?"; gen_list env (d - 1)]);
      1, (fun () -> S [A "if"; gen_bool env (d - 1); gen_bool env (d - 1); gen_bool env (d - 1)]);
    ]

and gen_string env d : sx =
  if d <= 0 then
    pick [
      3, (fun () -> gen_str_lit ());
      (if has_vars TStr env then 2 else 0), (fun () -> A (pick_var TStr env));
    ]
  else
    pick [
      3, (fun () -> gen_str_lit ());
      (if has_vars TStr env then 2 else 0), (fun () -> A (pick_var TStr env));
      3, (fun () -> S [A "string-append"; gen_string env (d - 1); gen_string env (d - 1)]);
      1, (fun () -> S [A "string-trim"; gen_string env (d - 1)]);
      1, (fun () -> S [A "number->string"; gen_int env (d - 1)]);
      1, (fun () ->
        (* appending "abcd" guarantees length >= 4, so bounds are safe *)
        S [A "string-sub";
           S [A "string-append"; gen_string env (d - 1); A "\"abcd\""];
           A "0"; A (string_of_int (rint 0 4))]);
      1, (fun () -> S [A "if"; gen_bool env (d - 1); gen_string env (d - 1); gen_string env (d - 1)]);
      1, (fun () -> S [A "->string"; gen_int env (d - 1)]);   (* f-string interpolation's lowering target *)
      2, (fun () -> gen_match TStr env d);
    ]

and gen_float env d : sx =
  if d <= 0 then
    pick [
      3, (fun () -> gen_float_lit ());
      (if has_vars TFloat env then 2 else 0), (fun () -> A (pick_var TFloat env));
    ]
  else
    pick [
      3, (fun () -> gen_float_lit ());
      (if has_vars TFloat env then 2 else 0), (fun () -> A (pick_var TFloat env));
      3, (fun () ->
        let op = [| "+"; "-"; "*" |].(Random.int 3) in
        S [A op; gen_float env (d - 1); gen_float env (d - 1)]);
      1, (fun () -> S [A "if"; gen_bool env (d - 1); gen_float env (d - 1); gen_float env (d - 1)]);
    ]

(* list of ints, statically NONEMPTY *)
and gen_list_ne env d : sx =
  if d <= 0 then
    let ne_vars = List.filter (fun v -> v.vty = TList && v.vne) (env.vars @ env.gvars) in
    if ne_vars <> [] && flip 0.4 then
      A (List.nth ne_vars (Random.int (List.length ne_vars))).vname
    else
      S (A "list" :: List.init (rint 1 3) (fun _ -> gen_int_lit ()))
  else
    pick [
      3, (fun () -> S (A "list" :: List.init (rint 1 3) (fun _ -> gen_int env (d - 1))));
      3, (fun () -> S [A "cons"; gen_int env (d - 1); gen_list env (d - 1)]);
      (if env.stdlib then 2 else 0), (fun () ->
        let a = rint 0 5 in let b = a + rint 1 6 in
        S [A "range"; A (string_of_int a); A (string_of_int b)]);
      (if env.stdlib then 1 else 0), (fun () ->
        let x = fresh "x" in
        let env' = { env with vars = { vname = x; vty = TInt; vne = false } :: env.vars } in
        S [A "map"; S [A "fn"; S [A x]; gen_int env' (d - 1)]; gen_list_ne env (d - 1)]);
      (let ne_vars = List.filter (fun v -> v.vty = TList && v.vne) (env.vars @ env.gvars) in
       (if ne_vars <> [] then 2 else 0)),
      (fun () ->
        let ne_vars = List.filter (fun v -> v.vty = TList && v.vne) (env.vars @ env.gvars) in
        A (List.nth ne_vars (Random.int (List.length ne_vars))).vname);
    ]

(* list of ints, possibly empty *)
and gen_list env d : sx =
  if d <= 0 then
    pick [
      2, (fun () -> A "nil");
      2, (fun () -> gen_list_ne env 0);
      (if has_vars TList env then 2 else 0), (fun () -> A (pick_var TList env));
    ]
  else
    pick [
      1, (fun () -> A "nil");
      4, (fun () -> gen_list_ne env d);
      (if has_vars TList env then 2 else 0), (fun () -> A (pick_var TList env));
      1, (fun () -> S [A "cdr"; gen_list_ne env (d - 1)]);
      (if env.stdlib then 1 else 0), (fun () ->
        S [A "take"; A (string_of_int (rint 0 4)); gen_list env (d - 1)]);
      (if env.stdlib then 1 else 0), (fun () ->
        let x = fresh "x" in
        let env' = { env with vars = { vname = x; vty = TInt; vne = false } :: env.vars } in
        S [A "filter"; S [A "fn"; S [A x]; gen_bool env' (d - 1)]; gen_list env (d - 1)]);
      1, (fun () -> S [A "apply"; A "list"; gen_list env (d - 1)]);  (* call-spread's lowering target *)
    ]

let gen_of_ty env d = function
  | TInt -> gen_int env d
  | TFloat -> gen_float env d
  | TBool -> gen_bool env d
  | TStr -> gen_string env d
  | TList -> gen_list env d

let random_ty env =
  pick [
    5, (fun () -> TInt);
    2, (fun () -> TBool);
    2, (fun () -> TStr);
    1, (fun () -> TFloat);
    (if env.stdlib then 2 else 1), (fun () -> TList);
  ]

let gen_printable env d : sx =
  let ty = random_ty env in
  gen_of_ty env d ty

(* --- statements (top-level forms) --- *)

(* generate a let-binding vector plus the extended env; bindings never
   reference each other (parallel-let-safe for the tree-walker) *)
let gen_bindings env d =
  let n = rint 1 2 in
  let rec go i acc_binds acc_vars =
    if i = 0 then (List.rev acc_binds, acc_vars)
    else begin
      let ty = random_ty env in
      let x = fresh "x" in
      let e = gen_of_ty env (d - 1) ty in
      let ne = (ty = TList) && (match e with
        | S (A "list" :: _ :: _) | S (A "cons" :: _) | S (A "range" :: _) -> true
        | _ -> false) in
      go (i - 1) (V [A x; e] :: acc_binds)
        ({ vname = x; vty = ty; vne = ne } :: acc_vars)
    end
  in
  let binds, new_vars = go n [] [] in
  let vec = V (List.concat_map (function V xs -> xs | x -> [x]) binds) in
  (vec, { env with vars = new_vars @ env.vars })

let stmt_print env d = [S [A "print"; gen_printable env d]]

let stmt_let_print env d =
  let vec, env' = gen_bindings env d in
  [S [A "let"; vec; S [A "print"; gen_printable env' (d - 1)]]]

let stmt_letstar_print env d =
  (* let* IS sequential; chain bindings *)
  let a = fresh "x" and b = fresh "x" in
  let env1 = { env with vars = { vname = a; vty = TInt; vne = false } :: env.vars } in
  let env2 = { env1 with vars = { vname = b; vty = TInt; vne = false } :: env1.vars } in
  [S [A "let*";
      V [A a; gen_int env (d - 1); A b; S [A "+"; A a; gen_int env1 (d - 1)]];
      S [A "print"; gen_int env2 (d - 1)]]]

let stmt_do_print env d =
  let n = rint 2 3 in
  let inner = List.init n (fun _ -> S [A "print"; gen_printable env (d - 1)]) in
  [S (A "do" :: inner)]

let stmt_do_scoped_def env d =
  (* A bare top-level `(do (def x ...) ...)` binds x
     BLOCK-LOCAL — referencing it after the `do`
     closes is an unbound-symbol error (a regression here would be
     a def leaking past the block, so the second statement below
     would print a stale value instead of erroring — a MISMATCH
     this generator would catch). Not added to
     `env.gvars`/`env.vars`: later statements must not see it either. *)
  let x = fresh "g" in
  let ty = random_ty env in
  let e = gen_of_ty env d ty in
  [S [A "do"; S [A "def"; A x; e]; S [A "print"; A x]];
   S [A "print"; A x]]

let stmt_def_value env d =
  (* (def x <expr>) — a VALUE binding: the RHS is
     evaluated at definition time and any later statement may reference x. *)
  let x = fresh "g" in
  let ty = random_ty env in
  let e = gen_of_ty env d ty in
  let ne = (ty = TList) && (match e with
    | S (A "list" :: _ :: _) | S (A "cons" :: _) | S (A "range" :: _) -> true
    | _ -> false) in
  env.gvars <- { vname = x; vty = ty; vne = ne } :: env.gvars;
  [S [A "def"; A x; e]; S [A "print"; A x]]

let stmt_def env d =
  let f = fresh "f" in
  let arity = rint 1 3 in
  let params = List.init arity (fun _ -> fresh "p") in
  let env' = { env with vars =
    List.map (fun p -> { vname = p; vty = TInt; vne = false }) params @ env.vars } in
  let body = gen_int env' d in
  env.fns <- (f, arity, false) :: env.fns;
  [S [A "def"; S (A f :: List.map (fun p -> A p) params); body]]

let stmt_def_rec env d =
  let f = fresh "f" in
  let n = fresh "p" in
  let env' = { env with vars = { vname = n; vty = TInt; vne = false } :: env.vars } in
  let op = if flip 0.8 then "+" else "*" in
  let step = gen_int env' (min 2 (d - 1)) in
  let base = gen_int_lit () in
  let def =
    S [A "def"; S [A f; A n];
       S [A "if"; S [A "<="; A n; A "0"];
          base;
          S [A op; step; S [A f; S [A "-"; A n; A "1"]]]]] in
  let call = S [A "print"; S [A f; A (string_of_int (rint 0 12))]] in
  env.fns <- (f, 1, true) :: env.fns;
  [def; call]

let stmt_with_config env d =
  let k = fresh "k" in
  let v = gen_int_lit () in
  let body =
    S [A "print";
       S [A "+"; S [A "config"; A (":" ^ k); gen_int_lit ()]; gen_int env (d - 1)]] in
  [S [A "with-config"; C [A (":" ^ k); v]; body]]

(* ------- full-grammar statements (audit-divergence probes) ------- *)

let ty_name = function TInt -> "int" | TStr -> "string" | TBool -> "bool" | _ -> "int"

let stmt_typed_let env d =
  (* (let [x : ty e] (print x)) — VM enforces, tree-walker discards *)
  let declared = [| TInt; TStr; TBool |].(Random.int 3) in
  let actual = if flip 0.6 then declared
               else [| TInt; TStr; TBool |].(Random.int 3) in
  let x = fresh "x" in
  [S [A "let"; V [A x; A ":"; A (ty_name declared); gen_of_ty env (d - 1) actual];
      S [A "print"; A x]]]

let stmt_typed_def env d =
  (* (def (f p) : ty body) then call *)
  let f = fresh "f" in
  let p = fresh "p" in
  let declared = [| TInt; TStr; TBool |].(Random.int 3) in
  let actual = if flip 0.6 then declared
               else [| TInt; TStr; TBool |].(Random.int 3) in
  let env' = { env with vars = { vname = p; vty = TInt; vne = false } :: env.vars } in
  [S [A "def"; S [A f; A p]; A ":"; A (ty_name declared); gen_of_ty env' (d - 1) actual];
   S [A "print"; S [A f; gen_int_lit ()]]]

let stmt_param_typed_def env d =
  (* (def (f p : ty) body) then call — per-parameter annotations are CHECKED
     (reader desugar); a 0.4-probability ill-typed call is a matched
     both-error probe, a well-typed call must return the body's value. *)
  let f = fresh "f" in
  let p = fresh "p" in
  let declared = [| TInt; TStr; TBool |].(Random.int 3) in
  let actual = if flip 0.6 then declared
               else [| TInt; TStr; TBool |].(Random.int 3) in
  let env' = { env with vars = { vname = p; vty = declared; vne = false } :: env.vars } in
  [S [A "def"; S [A f; A p; A ":"; A (ty_name declared)];
      gen_of_ty env' (d - 1) declared];
   S [A "print"; S [A f; gen_of_ty env (d - 1) actual]]]

let stmt_module env d =
  (* (import (module ...)) — VM compiles only EDef children *)
  let m = fresh "m" in
  let p = fresh "p" in
  let penv = { vars = [{ vname = p; vty = TInt; vne = false }];
               fns = []; stdlib = false; gvars = [] } in
  let def = S [A "def"; S [A m; A p]; gen_int penv (d - 1)] in
  let children =
    if flip 0.5 then [S [A "print"; gen_str_lit ()]; def]  (* non-def child *)
    else [def] in
  env.fns <- (m, 1, false) :: env.fns;
  [S [A "import"; S (A "module" :: children)];
   S [A "print"; S [A m; gen_int_lit ()]]]

let stmt_module_sibling env d =
  (* Module-body children see EARLIER siblings, letrec*-style
     — a sibling function def, a sibling value def, and a bare in-module
     statement all resolve through the module's own local slots (a
     regression here would resolve any of these globally at construction
     time and raise "unbound symbol" in the VM, since the tree-walker
     already threads `env_acc` forward across module children — e.g.
     exactly `(import (module (def (f x) ...) (print (f 1))))`). *)
  let f = fresh "m" and a = fresh "m" and b = fresh "m" in
  let p = fresh "p" in
  let penv = { vars = [{ vname = p; vty = TInt; vne = false }];
               fns = []; stdlib = false; gvars = [] } in
  let def_f = S [A "def"; S [A f; A p]; gen_int penv (d - 1)] in
  let def_a = S [A "def"; A a; gen_int_lit ()] in
  (* def_b: a value def referencing BOTH a sibling value (a) and a sibling
     function (f) *)
  let def_b = S [A "def"; A b; S [A "+"; A a; S [A f; A "1"]]] in
  (* bare module statement referencing siblings b and f *)
  let stmt = S [A "print"; S [A "+"; A b; S [A f; A "2"]]] in
  env.fns <- (f, 1, false) :: env.fns;
  env.gvars <- { vname = b; vty = TInt; vne = false } :: env.gvars;
  [S [A "import"; S [A "module"; def_f; def_a; def_b; stmt]];
   S [A "print"; S [A f; gen_int_lit ()]];
   S [A "print"; A b]]

let stmt_load_module env _d =
  (* (load-module "<abs stdlib>") then use a stdlib fn — an opcode probe *)
  env.stdlib <- true;
  [S [A "load-module"; A ("\"" ^ !stdlib_path ^ "\"")];
   S [A "print"; S [A "length"; S [A "range"; A "0"; A (string_of_int (rint 1 6))]]]]

(* Islands: a FIXED fixture island, pinned once at startup by running
   `pp --update` on a seed file (which also exercises the pin rewriter and
   fills the cache). Only pinned file: islands over this fixture are ever
   generated — network islands stay out (real nondeterminism). Setup failure
   degrades to disabled, never to a flaky grammar. *)
let island_fixture : (string * string) option Lazy.t = lazy (
  try
    let dir = Filename.temp_file "ppfuzz-island" "" in
    Sys.remove dir;
    Unix.mkdir dir 0o755;
    (* `.pp` dispatches to the brace reader, so the fixture's
       entry file (found by island.ml's entry_file via the literal name
       "entry.pp") must hold brace-surface text. The seed file below stays
       sexpr — it's read by `pp --update` as an argument file, so it gets
       the `.ppl` extension (sexpr, forever supported) instead. *)
    let oc = open_out (Filename.concat dir "entry.pp") in
    output_string oc "let isl-x = 42\ndef isl-add(n) { n + 5 }\n";
    close_out oc;
    let seed_f = Filename.temp_file "ppfuzz-island-seed" ".ppl" in
    let oc = open_out seed_f in
    output_string oc ("(import (island file:" ^ dir ^ "))\n(print isl-x)\n");
    close_out oc;
    let rc = Sys.command (Filename.quote !pp_bin ^ " --update "
                          ^ Filename.quote seed_f ^ " >/dev/null 2>&1") in
    if rc <> 0 then None
    else begin
      let ch = open_in seed_f in
      let line1 = input_line ch in
      close_in ch;
      let is_hex c = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') in
      let n = String.length line1 in
      let rec scan i =
        if i >= n then None
        else begin
          let j = ref i in
          while !j < n && is_hex line1.[!j] do incr j done;
          if !j - i = 64 then Some (String.sub line1 i 64)
          else scan (if !j > i then !j else i + 1)
        end
      in
      match scan 0 with
      | Some pin -> Some (dir, pin)
      | None -> None
    end
  with _ -> None)

let stmt_island env d =
  match Lazy.force island_fixture with
  | None -> stmt_print env d  (* setup failed: degrade, don't flake *)
  | Some (dir, pin) ->
      env.fns <- ("isl-add", 1, false) :: env.fns;
      [S [A "import"; S [A "island"; A ("file:" ^ dir); A ("\"" ^ pin ^ "\"")]];
       S [A "print"; S [A "isl-add"; A (string_of_int (rint 0 9))]]]

let stmt_config_computed env d =
  (* computed config key — VM requires compile-time literal *)
  let k = fresh "k" in
  let klen = String.length k in
  let k1 = String.sub k 0 (klen / 2) and k2 = String.sub k (klen / 2) (klen - klen / 2) in
  [S [A "with-config"; C [A (":" ^ k); gen_int_lit ()];
      S [A "print";
         S [A "config";
            S [A "string-append"; A ("\"" ^ k1 ^ "\""); A ("\"" ^ k2 ^ "\"")];
            gen_int env (d - 1)]]]]

let stmt_perform env d =
  (* perform log with no handler: builtin logs to stderr, returns nil *)
  if flip 0.5 then [S [A "perform"; A "log"; gen_string env (d - 1)]]
  else [S [A "print"; S [A "perform"; A "log"; gen_string env (d - 1)]]]

let stmt_with_handler env d =
  (* handler over log returning an int *)
  let m = fresh "p" in
  let henv = { env with vars = { vname = m; vty = TStr; vne = false } :: env.vars } in
  let hbody =
    if flip 0.5 then gen_int henv (d - 1)
    else S [A "do"; S [A "print"; S [A "string-append"; A "\"h:\""; A m]];
            gen_int henv (d - 1)] in
  [S [A "with-handler"; V [A "log"; S [A "fn"; S [A m]; hbody]];
      S [A "print"; S [A "perform"; A "log"; gen_string env (d - 1)]]]]

let stmt_handler_leak env d =
  (* with-handler whose body ends in a tail call — if the VM never pops the
     handler, a later perform diverges *)
  let f = fresh "f" in
  let p = fresh "p" in
  let env' = { env with vars = { vname = p; vty = TInt; vne = false } :: env.vars } in
  let m = fresh "p" in
  [S [A "def"; S [A f; A p]; gen_int env' (d - 1)];
   S [A "with-handler"; V [A "log"; S [A "fn"; S [A m]; A "77"]];
      S [A f; gen_int_lit ()]];
   S [A "print"; S [A "perform"; A "log"; gen_str_lit ()]]]

let stmt_deep_rec _env _d =
  (* deep recursion — stack-safety; tail and non-tail variants *)
  let f = fresh "f" in
  let n = fresh "p" in
  if flip 0.5 then begin
    let depth = [| 500; 2000; 5000 |].(Random.int 3) in
    [S [A "def"; S [A f; A n];
        S [A "if"; S [A "<="; A n; A "0"]; A "0";
           S [A "+"; A "1"; S [A f; S [A "-"; A n; A "1"]]]]];
     S [A "print"; S [A f; A (string_of_int depth)]]]
  end else begin
    let acc = fresh "p" in
    let depth = [| 5000; 20000 |].(Random.int 2) in
    [S [A "def"; S [A f; A n; A acc];
        S [A "if"; S [A "<="; A n; A "0"]; A acc;
           S [A f; S [A "-"; A n; A "1"]; S [A "+"; A acc; A "1"]]]];
     S [A "print"; S [A f; A (string_of_int depth); A "0"]]]
  end

let stmt_big_map env _d =
  (* must not reference stdlib fns unless the load form is actually present *)
  let prelude =
    if env.stdlib then []
    else begin
      env.stdlib <- true;
      [S [A "load"; A ("\"" ^ !stdlib_path ^ "\"")]]
    end in
  let x = fresh "x" in
  let n = rint 50 200 in
  prelude @
  [S [A "print";
      S [A "length";
         S [A "map"; S [A "fn"; S [A x]; S [A "+"; A x; A "1"]];
            S [A "range"; A "0"; A (string_of_int n)]]]]]

let stmt_eq_list env d =
  (* (= E E) with textually identical E — tree-walker dedups thunks *)
  let e = gen_list_ne env (d - 1) in
  [S [A "print"; S [A "="; e; e]]]

let stmt_seq_let env d =
  (* let binding referencing a sibling *)
  let a = fresh "x" and b = fresh "x" in
  [S [A "let"; V [A a; gen_int env (d - 1); A b; S [A "+"; A a; A "1"]];
      S [A "print"; A b]]]

let stmt_quote_special _env _d =
  if flip 0.5 then [S [A "print"; S [A "quote"; S [A "if"; A "1"; A "2"; A "3"]]]]
  else [S [A "print"; S [A "quote"; S [A "let"; V [A "x"; A "1"]; A "x"]]]]

(* The tree-walker matches structurally via Types.match_pattern and is
   immune to shadowing of car/cdr/nil?/not/error. This shadows every
   one of them in a `let` and runs a fixed match; the tree-walker must
   still print 6, so any regression surfaces as an ordinary fuzz
   MISMATCH. The whole fragment is emitted verbatim (a single atom)
   because its point is to be exactly this shape, not to vary.
   The shadows live inside an immediately-applied fn so they stay
   function-local. Supersedes the former tests/063 fixed oracle.
   `=` is deliberately NOT shadowed: the brace surface cannot express an
   operator-named binding, so the program would fail the roundtrip gate
   for surface reasons, not semantic ones. *)
let stmt_match_shadow _env _d =
  [A "((fn () (let (car 0 cdr 0 nil? 0 not 0 error 0) \
        (match (list 1 2 3) ((list a b c) (+ a (+ b c))) (_ 0)))))" ]
let stmt_defmacro _env _d =
  (* (defmacro (name x) (list (quote +) x x)) then (print (name N)) —
     the macro receives its argument FORM as a quoted value at expansion
     time (never evaluating it inside the macro body) and builds a new form
     with list/quote, converted back to syntax (Types.value_to_expr) before
     the evaluator ever sees it — a correct shared expansion point prints
     2*N identically. The argument is always a bare literal (never a
     side-effecting expr), so the doubled reference in the expansion can
     never double an observable effect — this arm is purely about expansion
     parity, not evaluation-order semantics. Fresh macro name per call site
     (fuzz.ml's `fresh`) since gen_program may pick this arm more than once
     in one program. *)
  let name = fresh "mac" in
  let n = rint 1 20 in
  [S [A "defmacro"; S [A name; A "x"];
      S [A "list"; S [A "quote"; A "+"]; A "x"; A "x"]];
   S [A "print"; S [A name; A (string_of_int n)]]]

